/* Peter 的每日雷达 — progressive enhancement only: theme, tag filters, card toggling, client-side search.
   All content is in the static HTML generated by build.py. */
(function () {
  const BASE = document.body.dataset.base || '/daily/';
  const CH = { news: '新闻', idea: '产品 Idea', oss: '开源' };
  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => [...r.querySelectorAll(s)];
  const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const I = {
    sun: '<svg viewBox="0 0 24 24"><circle cx="12" cy="12" r="4"/><path d="M12 2v2M12 20v2M4.9 4.9l1.4 1.4M17.7 17.7l1.4 1.4M2 12h2M20 12h2M4.9 19.1l1.4-1.4M17.7 6.3l1.4-1.4"/></svg>',
    moon: '<svg viewBox="0 0 24 24"><path d="M20 14.5A8 8 0 1 1 9.5 4a6.5 6.5 0 0 0 10.5 10.5z"/></svg>',
    auto: '<svg viewBox="0 0 24 24"><rect x="3" y="4" width="18" height="12" rx="2"/><path d="M8 20h8M12 16v4"/></svg>',
  };

  // ---------- theme: auto (system) -> light -> dark ----------
  const themeBtn = $('#themeBtn');
  const THEMES = ['auto', 'light', 'dark'], TL = { auto: '跟随系统', light: '浅色', dark: '深色' };
  function applyTheme(t) {
    if (t === 'auto') delete document.documentElement.dataset.theme; else document.documentElement.dataset.theme = t;
    themeBtn.innerHTML = I[t === 'auto' ? 'auto' : t === 'light' ? 'sun' : 'moon'];
    themeBtn.title = '主题：' + TL[t] + '（点击切换）';
  }
  let theme = 'auto'; try { theme = localStorage.getItem('hub-theme') || 'auto'; } catch (e) {}
  if (themeBtn) {
    applyTheme(theme);
    themeBtn.onclick = () => {
      theme = THEMES[(THEMES.indexOf(theme) + 1) % 3];
      try { theme === 'auto' ? localStorage.removeItem('hub-theme') : localStorage.setItem('hub-theme', theme); } catch (e) {}
      applyTheme(theme);
    };
  }

  const params = new URLSearchParams(location.search);
  const q = $('#q');

  // ---------- channel archive: tag chips (?tag=) ----------
  const arch = $('#arch');
  if (arch) {
    const apply = tag => {
      $$('.chip').forEach(c => c.setAttribute('aria-pressed', c.dataset.tag === tag));
      let shown = 0, dshow = 0;
      $$('#arch .day').forEach(day => {
        let n = 0;
        day.querySelectorAll('li').forEach(li => { const ok = !tag || li.dataset.tags.split('|').includes(tag); li.classList.toggle('hide', !ok); n += ok; });
        day.classList.toggle('hide', !n); shown += n; dshow += !!n;
      });
      $('#stat').textContent = tag ? `「${tag}」：${dshow} 天 · ${shown} 条` : `全部 ${shown} 条，按日期倒序`;
      $('#empty').classList.toggle('hide', shown > 0);
    };
    $$('.chip').forEach(c => c.onclick = () => {
      const tag = c.dataset.tag;
      history.replaceState(null, '', location.pathname + (tag ? '?tag=' + encodeURIComponent(tag) : ''));
      apply(tag);
    });
    apply(params.get('tag') || '');
  }

  // ---------- day detail: expandable cards, highlights, chips, #c-<id> deep links ----------
  const cards = $$('.card');
  if (cards.length) {
    const setOpen = (c, o) => { c.classList.toggle('open', o); const b = c.querySelector('.head'); b && b.setAttribute('aria-expanded', o); };
    cards.forEach(c => { const b = c.querySelector('.head'); if (b) b.onclick = () => setOpen(c, !c.classList.contains('open')); });
    $$('[data-open]').forEach(a => a.onclick = e => {
      e.preventDefault(); const c = document.getElementById('c-' + a.dataset.open); if (!c) return;
      setOpen(c, true); history.replaceState(null, '', '#c-' + a.dataset.open); c.scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
    const oa = $('#openAll'), ca = $('#closeAll');
    if (oa) { oa.onclick = () => cards.forEach(c => setOpen(c, true)); ca.onclick = () => cards.forEach(c => setOpen(c, false)); }
    if (!arch) $$('.chips .chip').forEach(ch => ch.onclick = () => {
      const tag = ch.dataset.tag; $$('.chips .chip').forEach(x => x.setAttribute('aria-pressed', x === ch));
      let n = 0; cards.forEach(c => { const ok = !tag || (c.dataset.tags || '').split('|').includes(tag); c.classList.toggle('hide', !ok); n += ok; });
      $('#empty') && $('#empty').classList.toggle('hide', n > 0);
    });
    const openHash = () => {
      const id = decodeURIComponent(location.hash.slice(1)); if (!id.startsWith('c-')) return;
      const c = document.getElementById(id); if (!c) return;
      setOpen(c, true); c.classList.add('flash');
      setTimeout(() => c.scrollIntoView({ block: 'start' }), 30); setTimeout(() => c.classList.remove('flash'), 2400);
    };
    openHash(); window.addEventListener('hashchange', openHash);
  }

  // ---------- search (/daily/search/?q=) ----------
  const root = $('#searchRoot');
  if (root) {
    let idx = null;
    const tagsHtml = (tags, n) => `<span class="tags">${tags.slice(0, n).map(t => `<span class="tag">${esc(t)}</span>`).join('')}</span>`;
    const render = term => {
      const t = term.trim().toLowerCase();
      document.title = (term.trim() ? `「${term.trim()}」 · ` : '') + '搜索 · Peter 的每日雷达';
      if (!t) { root.innerHTML = `<div class="page-h"><h1>搜索</h1><p class="lede">在上方输入关键词，例如「Java」「MCP」「支付」「Claude Code」。</p></div>`; return; }
      if (!idx) { root.innerHTML = '<div class="page-h"><h1>搜索</h1><p class="lede">正在载入索引…</p></div>'; return; }
      const words = t.split(/\s+/);
      const hay = i => i._h || (i._h = [i.title, i.summary, i.tags.join(' '), i.raw_tags.join(' '), i.text].join(' ').toLowerCase());
      const hits = idx.filter(i => words.every(w => hay(i).includes(w)))
        .map(i => ({ i, s: words.reduce((s, w) => s + (i.title.toLowerCase().includes(w) ? 3 : 0) + (i.tags.join(' ').toLowerCase().includes(w) ? 2 : 0), 0) }))
        .sort((a, b) => b.s - a.s || b.i.date.localeCompare(a.i.date)).map(x => x.i);
      const mark = s => { let h = esc(s); words.forEach(w => { const re = new RegExp(esc(w).replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'); h = h.replace(re, m => `<mark>${m}</mark>`); }); return h; };
      const grp = ['news', 'idea', 'oss'].map(ty => {
        const hs = hits.filter(i => i.type === ty); if (!hs.length) return '';
        return `<section class="res-group ch-${ty}"><h2><span class="badge">${CH[ty]}</span>${hs.length} 条</h2><ol class="res" style="list-style:none;margin:0;padding:0">${hs.slice(0, 30).map(i => `<li><a class="row" href="${BASE}${ty}/${i.date}/#c-${encodeURIComponent(i.id)}"><span class="d">${i.date}</span><span class="t">${mark(i.title)}</span><span></span><span class="m">${tagsHtml(i.tags, 4)}</span></a></li>`).join('')}</ol></section>`;
      }).join('');
      root.innerHTML = `<div class="page-h"><div class="eyebrow"><i></i>SEARCH</div><h1>「${esc(term)}」<small>${hits.length} 条结果</small></h1><p class="lede">在标题、摘要、标签和正文里搜索，标题命中优先。</p></div>${grp || '<p class="empty">没有找到，换个关键词试试</p>'}`;
    };
    const term0 = params.get('q') || '';
    if (q) {
      q.value = term0;
      $('#searchForm').onsubmit = e => { e.preventDefault(); history.replaceState(null, '', location.pathname + (q.value.trim() ? '?q=' + encodeURIComponent(q.value.trim()) : '')); render(q.value); };
      q.addEventListener('input', () => { history.replaceState(null, '', location.pathname + (q.value.trim() ? '?q=' + encodeURIComponent(q.value.trim()) : '')); render(q.value); });
    }
    render(term0);
    fetch(root.dataset.index).then(r => r.json()).then(j => { idx = j; render(q ? q.value : term0); })
      .catch(() => { root.innerHTML = '<p class="empty">搜索索引载入失败，请刷新重试。</p>'; });
  }
})();
